import { app } from 'electron'
import pkg from '../../package.json'

/**
 * Версия Зари.
 *
 * `app.getVersion()` отдаёт версию **Electron**, когда приложение запущено не из
 * упакованной папки: в разработке и во всех наших QA-прогонах это `43.2.0`, а не
 * `0.5.3`. Для строки «О программе» это просто неверная надпись, а для проверки
 * обновлений — тихий отказ: сравнение «43.2.0 против 0.5.3» навсегда даёт
 * «обновлений нет», и человек не узнает о выходе новой версии никогда. Ровно то
 * молчание, ради устранения которого проверка и писалась.
 *
 * Источник истины — `package.json`: из него же electron-builder берёт версию при
 * упаковке, так что упакованная сборка и сборка из исходников говорят одно и то
 * же. `app.getVersion()` остаётся запасным вариантом на случай, если поле
 * когда-нибудь пропадёт.
 */
export const APP_VERSION: string =
  typeof pkg.version === 'string' && pkg.version ? pkg.version : app.getVersion()
