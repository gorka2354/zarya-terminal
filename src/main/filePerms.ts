import { promises as fs } from 'fs'

/**
 * Права на файлы приложения.
 *
 * В `userData` лежат ключи провайдеров (`secrets.json`), история всех
 * выполненных команд (`history.jsonl`) и переписки с агентом. Node создаёт файлы
 * с правами по умолчанию — на Linux это 0644, то есть читать может любой
 * пользователь машины. Для файла с ключами это не мелочь.
 *
 * **Честно про Windows.** `chmod` там почти ничего не значит: NTFS живёт на ACL,
 * а Node отображает в него только флаг «только чтение». Так что на Windows эти
 * вызовы — не защита, а нейтральная операция; настоящая защита там в том, что
 * `userData` лежит внутри профиля пользователя. Смысл кода — Linux и macOS.
 *
 * Ошибки намеренно проглатываются: невозможность выставить права не повод
 * обрушить запуск приложения или потерять запись настроек.
 */

/** Только владелец читает и пишет. */
export const FILE_MODE = 0o600
/** Только владелец входит и перечисляет. */
export const DIR_MODE = 0o700

/**
 * Сузить права уже существующего файла.
 *
 * Нужно именно отдельным вызовом: файлы, созданные прошлыми версиями, остаются
 * с 0644 навсегда. `history.jsonl` дописывается и не пересоздаётся никогда, так
 * что без этого он не исправился бы сам ни при каких условиях.
 */
export async function hardenFile(path: string): Promise<void> {
  try {
    await fs.chmod(path, FILE_MODE)
  } catch {
    /* файла нет или ФС не поддерживает права — не наше дело */
  }
}

/** То же для каталога. */
export async function hardenDir(path: string): Promise<void> {
  try {
    await fs.chmod(path, DIR_MODE)
  } catch {
    /* см. выше */
  }
}
