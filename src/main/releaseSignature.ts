import { createHash, createPublicKey, verify } from 'crypto'

/**
 * Подпись релиза.
 *
 * Что она закрывает. Вся цепочка доверия к обновлению держалась на GitHub и
 * HTTPS: контрольные суммы считает CI — та же машина, что и собирает. При
 * захвате репозитория, утечке токена с правом пуша тегов или компрометации
 * зависимости хеш будет валидным, потому что его посчитает уже
 * скомпрометированная сборка. С автообновлением это тихое выполнение кода у
 * всех пользователей, без единого их клика.
 *
 * Поэтому список сумм подписывается ключом, которого НЕТ в CI: он живёт у
 * мейнтейнера (`scripts/gen-signing-key.mjs`), подпись ставится вручную после
 * публикации (`scripts/sign-release.mjs`). Приложение перед установкой требует
 * обе вещи: подпись списка валидна открытым ключом ниже И sha256 скачанного
 * файла совпадает со строкой в этом подписанном списке.
 *
 * Чего она НЕ закрывает — честно:
 *
 * - это не подпись Authenticode: у самого exe сертификата по-прежнему нет, и
 *   SmartScreen продолжит предупреждать при ручной установке;
 * - компрометацию машины мейнтейнера: там лежит закрытая часть;
 * - шаг подписи ручной по построению. Автоматизировать его в CI — значит
 *   положить ключ туда и потерять весь смысл.
 */

/**
 * Открытая часть ключа подписи (Ed25519, SPKI DER в base64).
 *
 * Меняется только вместе с ключом — а это событие, которое сломает обновление у
 * всех, кто уже поставил приложение: у них зашита прежняя открытая часть, и
 * новую подпись они не примут. Смена ключа = ручное обновление для всех.
 */
const PUBLIC_KEY_B64 = 'MCowBQYDK2VwAyEAyfV/AkUsmK/Ha6+ji8dcqOgS1vn7EpBiGQxIzKyLNuw='

/** Результат проверки — три разных случая, и интерфейс обязан их различать. */
export type SignatureVerdict =
  /** Подпись есть и она наша: файлам из этого списка можно верить. */
  | 'ok'
  /** Подписи к релизу нет вовсе — мейнтейнер её не приложил. */
  | 'missing'
  /** Подпись есть, но не сходится: либо не тот ключ, либо список подменили. */
  | 'bad'

/**
 * Подпись лежит рядом со списком сумм: `SHA256SUMS-0.5.8.txt` →
 * `SHA256SUMS-0.5.8.txt.sig`. Отдельным файлом, а не строкой внутри списка:
 * подписывается ровно то, что выложено, байт в байт.
 */
export function sigAssetName(sumsAssetName: string): string {
  return `${sumsAssetName}.sig`
}

/**
 * Подпись в файле — base64 (64 байта Ed25519). Пробелы и переводы строк
 * терпим: файл могли открыть в редакторе.
 */
export function parseSignature(text: string): Buffer | null {
  const clean = text.replace(/\s+/g, '')
  if (!/^[A-Za-z0-9+/]+={0,2}$/.test(clean)) return null
  const buf = Buffer.from(clean, 'base64')
  return buf.length === 64 ? buf : null
}

/**
 * Проверить подпись списка сумм.
 *
 * `sumsText` — файл ровно в том виде, в каком он выложен: подписывались его
 * байты, а не разобранная таблица. `sigText` — содержимое `.sig`; undefined
 * означает «подписи к релизу нет».
 */
export function verifyManifest(sumsText: string, sigText: string | undefined): SignatureVerdict {
  if (sigText === undefined) return 'missing'
  const sig = parseSignature(sigText)
  if (!sig) return 'bad'
  try {
    const key = createPublicKey({
      key: Buffer.from(PUBLIC_KEY_B64, 'base64'),
      format: 'der',
      type: 'spki'
    })
    // Ed25519 подписывает сообщение целиком: алгоритм дайджеста не указывается.
    return verify(null, Buffer.from(sumsText, 'utf8'), key, sig) ? 'ok' : 'bad'
  } catch {
    return 'bad'
  }
}

/** sha256 файла — та же величина, что стоит в подписанном списке. */
export function sha256Hex(data: Buffer): string {
  return createHash('sha256').update(data).digest('hex')
}
