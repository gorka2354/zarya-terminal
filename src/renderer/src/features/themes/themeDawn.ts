    panel: '#0a0f13',
    // Обводки — холодные, чтобы тёплый акцент был в интерфейсе единственным
    // тёплым пятном и читался как свет, а не как ещё одна деталь.
    border: 'rgba(150, 180, 200, 0.14)',
    borderStrong: 'rgba(255, 176, 92, 0.34)',
    fg: '#e4ecef',
    fgDim: '#9db0bb',
    fgFaint: '#5f7481',
    // Янтарь первого луча. Не красный: красный в этом интерфейсе означает
