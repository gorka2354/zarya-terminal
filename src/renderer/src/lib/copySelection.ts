/**
 * Что сейчас выделено у человека — в ленте или в терминале.
 *
 * ПОВОД. «Копировать» и в контекстном меню, и на Ctrl+Shift+C читало ТОЛЬКО
 * выделение xterm. В блочном режиме лента закрывает терминал собой: человек
 * выделяет мышью ответ агента, жмёт «Копировать» — а пункт неактивен, потому
 * что в буфере xterm за экраном не выделено ничего. Скопировать прозу или
 * вывод инструмента было нечем вовсе: кнопка копирования есть только у блока
 * кода.
 *
 * ПОРЯДОК ИСТОЧНИКОВ — ПО ТОМУ, ЧТО ЧЕЛОВЕК ВИДИТ. Сперва обычное выделение
 * DOM (лента, плашки, шапка), потом терминал. Наоборот было бы «скопировалось
 * не то»: в терминале выделение живёт до следующего щелчка и легко остаётся с
 * прошлого раза.
 */

/** Выделение в ленте и вообще в разметке — пусто, если человек ничего не выделял. */
export function domSelection(): string {
  if (typeof window === 'undefined') return ''
  const sel = window.getSelection?.()
  if (!sel || sel.isCollapsed) return ''
  /*
   * Выделение внутри поля ввода не наше дело: там работает встроенное
   * копирование браузера, и подменять его значило бы ломать привычное
   * поведение строки ввода и полей настроек.
   */
  const node = sel.anchorNode
  const el = node instanceof Element ? node : (node?.parentElement ?? null)
  if (el?.closest('input, textarea, [contenteditable="true"]')) return ''
  return sel.toString().trim()
}

/** Есть ли что копировать: лента ИЛИ терминал. */
export function selectionToCopy(termSelection: string | undefined): string {
  return domSelection() || (termSelection ?? '').trim()
}

/*
 * Прогону: что видит копирование прямо сейчас.
 *
 * Нужен одной проверке — что выделение внутри поля ввода мы НЕ перехватываем:
 * со стороны буфера обмена это не отличить от «скопировалось правильное».
 */
;(window as unknown as { __zaryaDomSelection?: () => string }).__zaryaDomSelection = domSelection
