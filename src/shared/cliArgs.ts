/**
 * `zarya .` — открыть проект одной командой.
 *
 * Аргументы командной строки не разбирались вовсе: терминал, который сам
 * запускается только мышью, — странный терминал. Из проводника («Открыть в
 * Заре»), из скрипта, из другого терминала — все три пути упираются в одно и то
 * же: передать папку при запуске.
 *
 * Разбор чистой функцией, потому что аргументы приходят из ТРЁХ разных мест и в
 * разной форме: у собранного приложения `argv[1]` — уже папка, у запуска через
 * `electron .` первый аргумент это сам проект Зари, а второй экземпляр приносит
 * argv чужого процесса вместе с ЕГО рабочей папкой. Проверить это на живом
 * запуске нельзя — там всегда один случай из трёх.
 */

/**
 * Ключи, которые Electron и Chromium подмешивают сами. Отличать их от папки по
 * ведущему дефису достаточно: путь, начинающийся с дефиса, в командной строке и
 * так недостижим без `./`.
 */
function isFlag(arg: string): boolean {
  return arg.startsWith('-')
}

/**
 * Найти папку среди аргументов. `null` — её там нет, и это нормальный запуск.
 *
 * `packaged` разделяет два мира. У собранного приложения всё после имени
 * исполняемого файла — от человека. При запуске из исходников (`electron .`)
 * первым аргументом идёт САМ проект Зари, и принять его за папку человека
 * значило бы открывать её при каждом запуске в разработке.
 */
export function folderArg(argv: readonly string[], packaged: boolean): string | null {
  // Первый элемент — путь к исполняемому файлу, он не аргумент.
  const rest = argv.slice(1).filter((a) => !isFlag(a))
  const args = packaged ? rest : rest.slice(1)
  const first = args.find((a) => a.trim())
  return first ? first.trim() : null
}

/**
 * Что делать с тем, что нашли. Отдельно от файловой системы: проверку
 * существования делает главный процесс, а здесь — только форма.
 *
 * Кавычки снимаем: проводник и оболочки передают путь с пробелами в кавычках, и
 * `"C:\Мои проекты"` без этого превратился бы в несуществующую папку с кавычкой
 * в имени.
 */
export function cleanArgPath(raw: string): string {
  let p = raw.trim()
  if (
    p.length >= 2 &&
    ((p.startsWith('"') && p.endsWith('"')) || (p.startsWith("'") && p.endsWith("'")))
  ) {
    p = p.slice(1, -1)
  }
  return p.trim()
}
