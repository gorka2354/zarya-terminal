/**
 * «Команда не найдена» — и стоит ли предлагать перезапуск оболочки.
 *
 * Случай, ради которого это написано, встречается у каждого: агент поставил
 * инструмент — rustup, node, gh, — и тут же предлагает его запустить. Установщик
 * дописал PATH, но ЖИВАЯ оболочка о нём не знает: переменные окружения читаются
 * при старте процесса и потом не меняются. Человек жмёт «запустить» и получает
 * «cargo не распознано» — при том, что cargo на диске есть, а в новой панели всё
 * работает.
 *
 * Заря видит и падение, и его причину, и умеет перезапустить оболочку в той же
 * папке. Промолчать здесь — оставить человека гадать между «не установилось»,
 * «установилось не туда» и «сломалось всё».
 *
 * Распознаём по тексту оболочки: свой у каждой, и переводы тоже свои.
 */

/** Признаки «такой команды нет» у оболочек, с которыми Заря работает. */
const ЗНАКИ: RegExp[] = [
  // PowerShell (англ. и рус. Windows)
  /is not recognized as (a|the) name of a cmdlet/i,
  /не распознано как имя командлета/i,
  /CommandNotFoundException/,
  // cmd.exe
  /is not recognized as an internal or external command/i,
  /не является внутренней или внешней командой/i,
  // bash / zsh / sh
  /command not found/i,
  /команда не найдена/i,
  /: not found\b/
]

/**
 * Похоже ли это на «команды нет».
 *
 * Смотрим ТОЛЬКО на вывод упавшей команды: у успешной такие слова означают
 * что-то другое (например, кто-то печатает справку), и предлагать перезапуск
 * там незачем.
 */
export function commandMissing(o: { output: string; exitCode?: number }): boolean {
  if (o.exitCode === undefined || o.exitCode === 0) return false
  const text = o.output.slice(0, 4000)
  return ЗНАКИ.some((r) => r.test(text))
}

/**
 * Имя программы, которой не хватило, — для честного текста подсказки.
 *
 * Вытаскиваем из первого слова команды: «cargo run» → «cargo». Если команда
 * пустая, подсказка обойдётся без имени — врать про «cargo» там, где его никто
 * не звал, хуже, чем сказать общее.
 */
export function missingName(command: string): string {
  const first = command.trim().split(/\s+/)[0] ?? ''
  // Обрезаем путь и расширение: `C:\tools\gh.exe` → `gh`.
  const base = first.split(/[\\/]/).pop() ?? first
  return base.replace(/\.(exe|cmd|bat|ps1)$/i, '')
}
