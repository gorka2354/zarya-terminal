/**
 * Подпись рабочего стола (вкладки).
 *
 * Вкладка — это и есть группа панелей, и до сих пор ей не хватало ровно одного:
 * имени. Строка свёрнутой вкладки подписывалась именем той панели, что была в
 * ней активной, — четыре разных проекта показывались одним именем, и оно ещё и
 * менялось, стоило переключить фокус внутри вкладки. Подпись, которая зависит
 * от того, куда человек ткнул минуту назад, — это не название группы.
 *
 * Поэтому: задал имя руками — показываем его; не задал — собираем из имён
 * панелей. Функция чистая и проверяется тестом: подпись видят чаще, чем любую
 * другую часть списка.
 */

/** Сколько имён показываем, прежде чем схлопнуть остаток в «+N». */
const SHOWN = 2

export function deskTitle(paneNames: string[], custom?: string): string {
  const own = custom?.trim()
  if (own) return own
  // Повторы убираем: три панели одного проекта — это «Заря», а не «Заря + Заря».
  const names = [...new Set(paneNames.map((n) => n.trim()).filter(Boolean))]
  if (!names.length) return 'Терминал'
  if (names.length <= SHOWN) return names.join(' + ')
  return `${names.slice(0, SHOWN).join(' + ')} +${names.length - SHOWN}`
}
