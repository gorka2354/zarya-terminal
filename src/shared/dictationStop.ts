/**
 * Когда диктовка заканчивается сама.
 *
 * У микрофона два способа включиться, и заканчиваются они по-разному:
 *
 *   ЗАЖАЛ КЛАВИШУ  — говорит, пока держит. Тишина посреди фразы ничего не
 *                    значит: человек думает, а не закончил. Останавливает
 *                    отпускание клавиши, и только оно.
 *   НАЖАЛ ЗНАЧОК   — клавишу никто не держит, и единственный признак конца —
 *                    тишина после речи. Без него запись идёт, пока человек не
 *                    сообразит нажать второй раз.
 *
 * Правило жило внутри компонента одной строкой `heard && !ptt`, и в ней
 * пряталось сразу две ошибки — обе с одним симптомом: «слова вставляются только
 * после второго нажатия».
 *
 * ПЕРВАЯ: флаг «клавишу держат» ставился по нажатию, а снимался только по
 * отпусканию ТОЙ ЖЕ клавиши. Стоило окну потерять фокус между этими событиями
 * (Alt+Tab, чужое окно, комбинация, перехваченная системой) — `keyup` уходил не
 * нам, флаг застревал в «держат», и с этого мига ЛЮБАЯ запись, начатая мышью,
 * переставала останавливаться сама.
 *
 * ВТОРАЯ: порог речи был константой 0.12 по пику. Микрофон, который отдаёт
 * тише (петличка без усиления, дальний ноутбучный, слабый autoGain), НИКОГДА её
 * не переступал — «речь звучала» не выставлялось, и автостоп не включался ни
 * разу за всё время работы. Распознавание при этом работало прекрасно: модель
 * тихую речь разбирает, а наш порог — нет. Поэтому порог теперь считается от
 * САМОГО ГРОМКОГО места этой записи, а константа осталась только полом против
 * шума вентилятора.
 *
 * Решение вынесено сюда: его видно целиком и его можно проверить.
 */

export interface StopInput {
  /** Уровень входа 0..1 прямо сейчас. */
  level: number
  /** Речь в этой записи уже звучала — до неё тишина ничего не значит. */
  heard: boolean
  /** Самое громкое место этой записи (ведётся этой же функцией). */
  peak: number
  /** Момент, с которого длится тишина (0 — тишины нет). */
  quietSince: number
  /** Сейчас, мс. Передаётся снаружи: время — не дело чистой функции. */
  now: number
  /**
   * Запись начата УДЕРЖАНИЕМ клавиши.
   *
   * Только это отменяет автостоп. Запись, начатая значком, останавливается по
   * тишине всегда — независимо от того, что случилось с чужими клавишами.
   */
  heldByKey: boolean
}

export interface StopDecision {
  heard: boolean
  peak: number
  quietSince: number
  /** Пора заканчивать запись. */
  stop: boolean
}

/**
 * Ниже этого — не речь ни при каком усилении.
 *
 * Пол против шума: дыхание, вентилятор, гул сети. Занизить — и запись начнёт
 * «слышать речь» в тишине, а потом обрываться сама посреди раздумья.
 */
export const NOISE_FLOOR = 0.035

/**
 * Какую долю от самого громкого места считаем речью.
 *
 * Половина пика — это заметно громче фона и заметно тише крика. Так порог
 * подстраивается под микрофон: у громкого он поднимется, у тихого опустится, и
 * автостоп станет работать у обоих.
 */
export const SPEECH_RATIO = 0.5

/** Столько тишины после речи — и хватит. */
export const QUIET_MS = 1500

/** Порог речи для записи с таким пиком. */
export function speechLevel(peak: number): number {
  return Math.max(NOISE_FLOOR, peak * SPEECH_RATIO)
}

export function dictationStop(i: StopInput): StopDecision {
  const peak = Math.max(i.peak, i.level)
  if (i.level > speechLevel(peak)) return { heard: true, peak, quietSince: 0, stop: false }
  // Речи ещё не было: человек молчит перед началом — ждём сколько угодно.
  if (!i.heard) return { heard: false, peak, quietSince: 0, stop: false }
  if (i.heldByKey) return { heard: true, peak, quietSince: 0, stop: false }
  const since = i.quietSince || i.now
  return { heard: true, peak, quietSince: since, stop: i.now - since > QUIET_MS }
}
