/**
 * Инструменты, которые правят файлы, — и только они.
 *
 * Нужны промежуточной ступени допуска: «правки без спроса, команды со спросом».
 * В консоли это `acceptEdits`, самый рабочий режим рефакторинга — там, где
 * каждая вторая карточка это `Edit` одного и того же файла, и человек всё равно
 * жмёт «да» двадцать раз подряд.
 *
 * Список закрытый и проверяемый намеренно. Ошибка в одну сторону — лишний
 * вопрос; в другую — молча выполненная команда оболочки, которую в этом режиме
 * никто не разрешал. Поэтому `Bash`, `Task`, `WebFetch` и всё незнакомое сюда
 * НЕ попадают: незнакомый инструмент по умолчанию спрашивает.
 */

/** Правки файлов у Claude Code и совместимых движков. */
const EDIT_TOOLS = new Set([
  'edit',
  'write',
  'multiedit',
  'notebookedit',
  'applypatch',
  'apply_patch',
  'str_replace_editor',
  'str_replace_based_edit_tool',
  'create_file',
  'update_file'
])

/**
 * Правит ли этот вызов файлы — и, значит, накрывается ли ступенью «правки без
 * спроса».
 *
 * Инструменты MCP (`mcp__server__name`) сюда не относятся никогда: что делает
 * чужой сервер, мы не знаем, а имя вида `mcp__fs__write_file` слишком похоже на
 * правку, чтобы угадывать. Такой вызов остаётся с вопросом.
 */
export function isEditTool(name: unknown): boolean {
  if (typeof name !== 'string' || !name) return false
  if (name.startsWith('mcp__')) return false
  return EDIT_TOOLS.has(name.toLowerCase())
}
