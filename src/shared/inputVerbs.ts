/**
 * Строки, которые НЕ уходят агенту: их исполняет сама Заря.
 *
 * В консоли таких две: строка с решёткой кладётся в память проекта, а «/copy»
 * забирает последний ответ в буфер обмена. Обе выглядят как обычный ввод, и
 * поэтому решение «это не сообщение» должно приниматься одним правилом, а не
 * россыпью проверок по месту.
 */

/**
 * Что записать в память, если строка начата с решётки.
 *
 * `null` — обычное сообщение. Пустая решётка тоже `null`: «#» без текста — это
 * начатая и брошенная мысль, а не просьба что-то запомнить.
 *
 * Заголовок Markdown («# Заголовок») сюда попадает намеренно: строка ввода — не
 * редактор, и человек, набравший решётку первым символом, почти наверняка хочет
 * записать правило, а не оформить текст.
 */
export function memoryNote(text: string): string | null {
  const m = /^\s*#\s*(.+)$/s.exec(text)
  if (!m) return null
  const note = m[1].trim()
  return note || null
}

/** Команды, которые Заря исполняет сама, не спрашивая движок. */
export type LocalVerb = 'copy'

/**
 * Локальная команда в строке — или `null`.
 *
 * Список нарочно короткий: всё, что умеет движок, должно идти движку, иначе
 * Заря начнёт перехватывать команды, о которых ничего не знает.
 */
export function localVerb(text: string): LocalVerb | null {
  const one = text.trim().toLowerCase()
  if (one === '/copy' || one === '/копировать') return 'copy'
  return null
}
