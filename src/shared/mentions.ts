/**
 * Упоминание файла через «@» — то, чем в консоли приносят файл в запрос.
 *
 * Без него путь набирают по памяти или тащат мышью: файловый поиск в Заре есть
 * (Ctrl+P), но он ОТКРЫВАЕТ файл в редакторе, а не кладёт его имя в строку — то
 * есть отвечает на другой вопрос.
 *
 * Разбор строки вынесен сюда чистыми функциями по образцу «/»-команд: где
 * начинается упоминание и чем оно кончается, решает не поле ввода, а правило,
 * которое можно проверить построчно.
 */

/**
 * Что набрано после «@» под кареткой — или `null`, если упоминания здесь нет.
 *
 * Правила выбраны по тому, как «@» встречается в обычном тексте:
 * - перед «@» должен быть пробел или начало строки, иначе почта (`a@b.com`) и
 *   декораторы (`@media`) превращались бы в поиск файлов на каждом нажатии;
 * - внутри упоминания пробелов нет — путь кончается там, где начинается фраза.
 */
export function mentionQuery(text: string, caret: number): string | null {
  const upto = text.slice(0, caret)
  const m = /(^|\s)@([^\s@]*)$/.exec(upto)
  return m ? m[2] : null
}

/**
 * Подставить выбранный путь вместо набранного упоминания.
 *
 * Возвращает новый текст и позицию каретки: она встаёт СРАЗУ после пути с
 * пробелом — упоминание почти всегда часть фразы («@src/main.ts почему тут…»),
 * и доводить каретку руками пришлось бы каждый раз.
 */
export function applyMention(
  text: string,
  caret: number,
  path: string
): { text: string; caret: number } {
  const upto = text.slice(0, caret)
  const m = /(^|\s)@([^\s@]*)$/.exec(upto)
  if (!m) return { text, caret }
  const start = upto.length - m[2].length - 1
  const insert = `@${path} `
  const next = text.slice(0, start) + insert + text.slice(caret)
  return { text: next, caret: start + insert.length }
}
