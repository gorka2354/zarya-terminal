/**
 * Путь файла, который человек кладёт в командную строку жестом.
 *
 * Экранируем ВСЕГДА, а не только при пробеле. Кавычки нужны не пробелу: `&`,
 * `|`, `;`, `(`, `$` рвут строку не хуже, а имя файла приходит из файловой
 * системы — то есть из чужих рук (склонированный репозиторий, распакованный
 * архив, загрузка). Путь, вставленный в приглашение, человек отправляет по Enter
 * не глядя: `C:\R&D\notes.txt` без кавычек cmd разорвёт на `&` и выполнит хвост
 * отдельной командой.
 */

/**
 * Взять путь в кавычки так, как поймёт оболочка.
 *
 * Windows (cmd, PowerShell) — двойные кавычки: внутреннюю двойную кавычку
 * файловая система в имя не пустит, всё остальное внутри кавычек безопасно.
 * POSIX — одинарные с классическим приёмом `'\''` для внутренней одинарной:
 * внутри одинарных кавычек оболочка не разбирает ничего вообще.
 */
export function quotePath(path: string, windows: boolean): string {
  if (!path) return ''
  if (windows) return `"${path.replace(/"/g, '')}"`
  return `'${path.replace(/'/g, "'\\''")}'`
}
