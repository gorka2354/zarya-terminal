/**
 * Заголовок, которым программа подписывает вкладку (`OSC 0` / `OSC 2`).
 *
 * inc-31 научил Зарю его принимать: `ssh prod`, `vim`, `htop` называют себя
 * сами, и четыре панели в одном проекте перестали зваться одинаково.
 *
 * Но подписывается не только полезное. **Windows PowerShell при старте шлёт
 * заголовком полный путь к собственному exe** — и панель получала имя
 * `C:\WINDOWS\System32\WindowsPowerShell\v1.0\powershell.exe`. В списке сессий
 * четыре такие панели неотличимы друг от друга и не говорят ни о папке, ни о
 * работе: имя стало ХУЖЕ того, что было до inc-31, когда бралось имя каталога.
 *
 * Отбор чистой функцией, потому что заголовок приходит из чужого потока и
 * проверить его в живом терминале дороже, чем описать правило.
 */

/**
 * Годится ли заголовок в имя панели. `null` — не годится, оставить прежнее.
 *
 * @param raw как пришло от программы, вместе с управляющими знаками
 */
export function programTitle(raw: string): string | null {
  /*
   * Управляющие знаки выкидываем ПО КОДУ, а не регулярным выражением с
   * литеральными байтами: такое выражение нечитаемо в исходнике и ломается от
   * любой правки файла инструментом, который трогает кодировку.
   */
  let clean = ''
  for (const ch of raw) {
    const code = ch.codePointAt(0) ?? 0
    if (code >= 0x20 && code !== 0x7f) clean += ch
  }
  clean = clean.trim()
  if (!clean) return null
  if (isSelfPath(clean)) return null
  return clean.length > 60 ? `${clean.slice(0, 60)}…` : clean
}

/**
 * Самоподпись оболочки: путь к исполняемому файлу и ничего больше.
 *
 * Проверяем ФОРМУ, а не совпадение с настоящим путём нашей оболочки. Так
 * отсекается и `cmd.exe`, и чужая оболочка, о профиле которой мы ничего не
 * знаем, — а полезные подписи мимо не проходят: `vim` шлёт
 * «file.txt (~/proj) - VIM», ssh — «egor@egorka23», и ни то, ни другое не
 * кончается на `.exe`.
 *
 * Путь без разделителей (просто `powershell.exe`) тоже считаем самоподписью:
 * имя исполняемого файла в подписи вкладки не говорит человеку ничего, чего он
 * не видит по значку профиля.
 */
function isSelfPath(title: string): boolean {
  if (/\s/.test(title)) {
    // С пробелом это уже фраза, а не путь: «npm run build» или «Program Files»
    // в середине пути. Второе отсекаем ниже отдельно.
    const looksLikePath = /^[a-zA-Z]:[\\/]/.test(title) || title.startsWith('/')
    if (!looksLikePath) return false
  }
  return /\.(exe|com|bat|cmd|ps1)$/i.test(title)
}
