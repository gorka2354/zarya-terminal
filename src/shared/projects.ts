/**
 * Список проектов — папки, с которыми работают.
 *
 * Правило списка живёт отдельно от действий над ним: порядок и потолок человек
 * видит каждый раз, открывая меню папок, а ошибка здесь не падает и не светится
 * — она молча перемешивает проекты или теряет тот, с которым работали вчера.
 * Поэтому это чистая функция, которую проверяет тест, а не строчка внутри
 * обработчика клика.
 */

/** Сколько папок держим. Дальше список перестаёт быть списком. */
export const PROJECTS_MAX = 12

/** Список с папкой наверху: без дублей и не длиннее потолка. */
export function withProject(list: string[], dir: string, max = PROJECTS_MAX): string[] {
  const clean = dir.trim()
  if (!clean) return list
  // Дубли ищем по смыслу пути, а не по строке: иначе одна папка, выбранная
  // разными путями, займёт в списке две строки.
  return [clean, ...list.filter((b) => !samePath(b, clean))].slice(0, max)
}

/**
 * Одна ли это папка.
 *
 * Путь до одной и той же папки приходит в разном виде: диалог выбора отдаёт
 * `C:\code\cv`, оболочка сообщает `C:/code/cv`, а из настроек он мог прийти с
 * хвостовым слэшем. Посимвольное сравнение объявляло их разными, и метка
 * «открыто сейчас» гасла на проекте, который прямо сейчас открыт, — интерфейс
 * говорил неправду о происходящем.
 *
 * Регистр игнорируем только у путей с буквой диска: на Linux `~/Code` и
 * `~/code` — разные папки, и слить их значило бы соврать в другую сторону.
 */
export function samePath(a: string, b: string): boolean {
  const norm = (p: string): string =>
    p
      .trim()
      .replace(/[\\/]+/g, '/')
      .replace(/\/+$/, '')
  const x = norm(a)
  const y = norm(b)
  if (!x || !y) return false
  const windowsish = /^[a-z]:/i.test(x) && /^[a-z]:/i.test(y)
  return windowsish ? x.toLowerCase() === y.toLowerCase() : x === y
}
