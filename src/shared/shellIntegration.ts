/**
 * Как рассказать о себе оболочке, которая не умеет грузить наш скрипт.
 *
 * PowerShell, bash и zsh принимают файл при запуске — им мы просто передаём
 * путь. Две оболочки такой возможности не дают, и обе живут на Windows:
 *
 *   • **Командная строка** (`cmd.exe`) — ни rc-файла, ни хуков. Единственное,
 *     что она печатает сама и по своей воле, это приглашение; значит и сказать
 *     что-либо она может только через него.
 *
 *   • **WSL** — `wsl.exe` запускает оболочку ВНУТРИ дистрибутива, и наши
 *     аргументы до неё не доходят. Зато переменные окружения — доходят (через
 *     `WSLENV`), а bash читает `PROMPT_COMMAND` из окружения. Это и есть шов.
 *
 * ЗАЧЕМ ВООБЩЕ. Без этого панель врала о том, где она: каталог замирал на том,
 * с которого её открыли, и не двигался ни на один `cd`. А каталог панели — не
 * подпись: его получает агент как свою рабочую папку. То есть «панель показывает
 * не тот каталог» означает «агент правит не тот проект».
 *
 * Здесь только СБОРКА СТРОК — чтобы её можно было проверить без запуска
 * оболочки (см. tests/shellIntegration.test.ts). Всё, что связано с процессом,
 * остаётся в ptyManager.
 */

/** Строка приглашения по умолчанию у `cmd.exe` — путь и «больше». */
const CMD_DEFAULT_PROMPT = '$P$G'

/**
 * Приглашение `cmd.exe`, которое заодно сообщает каталог.
 *
 * `$e` — символ ESC, `$P` — текущий диск и путь. Получается `OSC 9;9;<путь>`,
 * та же последовательность, которой пользуется Терминал Windows, — Заря её уже
 * понимает. Печатается ПЕРЕД приглашением и завершается ST, поэтому на экране
 * ничего не появляется.
 *
 * Прежнее приглашение сохраняем целиком: человек мог настроить его под себя, и
 * подменять чужую настройку ради своей подсказки — не наше дело. Если своего
 * нет, подставляем ровно то, что `cmd.exe` показал бы сам.
 */
export function cmdPrompt(prev?: string): string {
  return '$e]9;9;$P$e\\' + (prev && prev.trim() ? prev : CMD_DEFAULT_PROMPT)
}

/** Что WSL обязан пронести внутрь дистрибутива. `/p` — «это путь, переведи». */
const WSL_SHARE = [
  'ZARYA_SI/p',
  'ZARYA_SI_BOOTSTRAP',
  'ZARYA_WSL_HOST',
  'ZARYA_NONCE',
  'PROMPT_COMMAND',
  'ZARYA',
  'ZARYA_VERSION',
  'TERM_PROGRAM',
  'TERM_PROGRAM_VERSION',
  'COLORTERM'
]

/**
 * Окружение, из которого bash внутри WSL сам подключит нашу интеграцию.
 *
 * `PROMPT_COMMAND` bash читает из окружения и выполняет перед первым же
 * приглашением — то есть до того, как человек успеет что-либо набрать. Скрипт
 * снимает переменную с себя (`unset`), поэтому подключение случается один раз, а
 * не на каждой строке.
 *
 * ПОЧЕМУ НЕ `--rcfile`, как у Git Bash. `wsl.exe -d <дистрибутив>` запускает
 * оболочку ВХОДА (login shell): она читает `/etc/profile` и `~/.profile`.
 * Подменив запуск на `bash --rcfile … -i`, мы получили бы обычную интерактивную
 * оболочку — без profile, то есть с другим PATH и другим окружением, чем то, к
 * которому человек привык. Ради подсказки ломать чужую оболочку нельзя.
 *
 * ОГОВОРКА, И ОНА ЧЕСТНАЯ. Свой `PROMPT_COMMAND`, унаследованный от Windows,
 * будет заменён: это единственный шов в уже запущенную оболочку, и делить его не
 * с кем. На Windows такую переменную не ставит никто (она из мира bash), так что
 * случай теоретический — но замалчивать его не будем.
 *
 * `WSLENV` дописываем к тому, что там было: он мог быть настроен человеком, и
 * затереть его значило бы отобрать у него уже работающий проброс.
 */
export function wslIntegrationEnv(scriptPath: string, prevWslEnv?: string): Record<string, string> {
  const prev = (prevWslEnv ?? '').split(':').filter(Boolean)
  const mine = WSL_SHARE.filter((v) => !prev.includes(v))
  return {
    ZARYA_SI: scriptPath,
    ZARYA_SI_BOOTSTRAP: '1',
    ZARYA_WSL_HOST: '1',
    PROMPT_COMMAND: 'unset PROMPT_COMMAND; source "$ZARYA_SI"',
    WSLENV: [...prev, ...mine].join(':')
  }
}

/**
 * Можно ли РУЧАТЬСЯ, что в этой оболочке интеграция поднимется.
 *
 * Отвечает на вопрос «панель точно рассказывает о командах», а не «мы что-то ей
 * подсунули». Разница не формальная: этим признаком Заря решает, говорить ли
 * агенту «эта оболочка о командах не рассказывает» вместо пустого списка. Пустой
 * список агент прочитает единственным доступным ему образом — «человек ничего не
 * запускал» — и скажет это вслух тому, у кого экран полон команд.
 *
 * Ручаемся только там, где оболочку выбрали МЫ и скрипт отдали ей прямо в руки:
 * PowerShell, bash, zsh.
 *
 * `cmd` — нет: у Командной строки есть только приглашение, и через него она
 * сообщает каталог. О командах — ни слова, блоков там не будет никогда.
 *
 * `wsl` — тоже нет, и это не осторожность ради осторожности. Внутри
 * дистрибутива оболочку выбирает не Заря: там может оказаться zsh, fish или
 * busybox, которые про `PROMPT_COMMAND` ничего не знают. Пообещав блоки, мы
 * получили бы ровно ту ложь, от которой признак и заведён. Когда оболочка всё же
 * bash, блоки приходят — и признак становится не нужен: список уже не пуст.
 */
export function integrationGuaranteed(kind: string): boolean {
  return kind === 'powershell' || kind === 'bash' || kind === 'zsh'
}
