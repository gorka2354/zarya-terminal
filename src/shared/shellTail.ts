/**
 * Хвост консоли: последние команды ЧЕЛОВЕКА, уезжающие агенту вместе с ходом.
 *
 * ПОВОД. Настройка «Блоков контекста» обещала «прикреплять к запросу
 * автоматически», а работала только у встроенного провайдера: её читал
 * `buildSystemPrompt()`, который зовётся из `dispatchChat()`. Claude Code ходит
 * другой дорогой и команд человека не видел вовсе. Человек включал настройку и
 * получал не то, что она обещает.
 *
 * ПОЧЕМУ ЧИСТОЙ ФУНКЦИЕЙ. Формат здесь — не украшение, а защита: вывод чужой
 * программы попадает в контекст модели, и от того, как он обёрнут, зависит,
 * прочитает ли она «ignore previous instructions» как данные или как приказ.
 * Такое место обязано быть проверяемым отдельно от React, стора и движка.
 *
 * ПОЧЕМУ СИМВОЛЫ, А НЕ ТОКЕНЫ. Заря принципиально не считает токены сама: все
 * числа в интерфейсе приходят от движка (см. `cost.ts`, `contextParts.ts`).
 * Написать здесь «примерно 600 токенов» значило бы назвать цифру, за которую
 * никто не отвечает. Поэтому потолки посимвольные — и называются символами.
 */

/** Блок команды в том виде, в каком он нужен хвосту. Подмножество `BlockRecord`. */
export interface TailBlock {
  command: string
  exitCode?: number
  output: string
}

/**
 * Подписи приходят снаружи, а не берутся из i18n здесь.
 *
 * Так один и тот же формат обслуживает и встроенного провайдера, и Claude Code,
 * оставаясь чистым: словарь живёт в рендерере, а функция — общая.
 */
export interface TailLabels {
  /** Вступление: это НЕДОВЕРЕННЫЕ данные, инструкции внутри не выполнять. */
  intro: string
  /** Команда неизвестна — интеграция с оболочкой ещё не прислала строку. */
  unknownCmd: string
  /** Пометка о том, что вывод обрезан. */
  truncated: string
  /** Чем заменена попытка подделать закрывающий маркер. */
  stripped: string
}

/** Что именно уехало — для видимого следа в ленте. */
export interface TailUsed {
  command: string
  exitCode?: number
}

export interface ShellTail {
  /** Готовый текст для модели. */
  text: string
  /** Команды, которые в него вошли, в хронологическом порядке. */
  used: TailUsed[]
  /** Сколько блоков не влезло в потолок. Ноль — значит уехало всё, что просили. */
  dropped: number
}

/** Потолок вывода ОДНОГО блока. Столько же было у встроенного провайдера. */
export const PER_BLOCK_CAP = 1500
/**
 * Потолок всего хвоста.
 *
 * Нужен именно суммарный: три блока по полторы тысячи символов — это уже
 * заметная прибавка к КАЖДОМУ ходу, а человек, поставивший в настройке 20,
 * не подписывался на тридцать тысяч символов в каждом запросе.
 */
export const TOTAL_CAP = 5000
/**
 * Потолок САМОЙ СТРОКИ КОМАНДЫ.
 *
 * Отдельно от вывода, потому что она печатается вне обёртки и без своего
 * предела обходила суммарный: команда в оболочку приходит целой строкой, а
 * вставить туда можно и мегабайт. Двухсот символов хватает, чтобы узнать
 * команду; всё остальное — её аргументы, и они не стоят места в каждом ходе.
 */
export const COMMAND_CAP = 200

/** Маркер, внутри которого едет чужой вывод. */
const MARK = 'untrusted-terminal-output'
const MARK_RE = new RegExp(`</?${MARK}>`, 'gi')

/** Хвост строки с пометкой об обрезке — свежее важнее начала. */
function tailClip(s: string, max: number, truncated: string): string {
  return s.length > max ? `${truncated}\n${s.slice(-max)}` : s
}

/**
 * Строка команды — тоже недоверенная, и печатается она ВНЕ обёртки.
 *
 * Поймано тестом: `echo </untrusted-terminal-output>` подделывал закрывающий
 * маркер прямо в заголовке блока, куда чистка вывода не достаёт. Переводы строк
 * схлопываем по той же причине — многострочная команда иначе дорисовала бы
 * собственные `exit:` и маркеры и подменила структуру блока.
 *
 * Строку команды присылает интеграция с оболочкой, и нонсованный канал её
 * защищает — но полагаться на это здесь нельзя: чистка стоит одну замену, а
 * рассуждение «сюда не дотянутся» стоило бы дыры, если дотянутся.
 */
function commandLine(command: string, labels: TailLabels): string {
  const safe = (command ?? '').replace(MARK_RE, labels.stripped).replace(/\s*[\r\n]+\s*/g, ' ⏎ ')
  const trimmed = safe.trim()
  if (!trimmed) return labels.unknownCmd
  /*
   * Команду тоже режем — ревью поймало обход суммарного потолка.
   *
   * Потолок применялся только к ВЫВОДУ, а строка команды шла как есть. Одна
   * вставленная heredoc или base64-строка на десятки килобайт уезжала целиком
   * и в КАЖДОМ ходе, пока человек не запустит другую: заявленные пять тысяч
   * символов оказывались обещанием, а не пределом.
   *
   * Режем НАЧАЛО, а не хвост: команду узнают по первым словам, и `npm run …`
   * говорит больше, чем последние двести символов её аргументов.
   */
  return trimmed.length > COMMAND_CAP
    ? `${trimmed.slice(0, COMMAND_CAP)} ${labels.truncated}`
    : trimmed
}

/** Текст одного блока целиком, уже безопасно обёрнутый. */
function blockText(b: TailBlock, labels: TailLabels): string {
  const lines = [`$ ${commandLine(b.command, labels)}`, `exit: ${b.exitCode ?? '—'}`]
  const out = tailClip(b.output ?? '', PER_BLOCK_CAP, labels.truncated)
  if (out) {
    lines.push(`<${MARK}>`)
    // Полезная нагрузка может попытаться закрыть маркер раньше времени и
    // выдать остаток за обычный текст разговора. Гасим обе скобки.
    lines.push(out.replace(MARK_RE, labels.stripped))
    lines.push(`</${MARK}>`)
  }
  return lines.join('\n')
}

/**
 * Собрать хвост из последних `n` блоков.
 *
 * Идём С КОНЦА и останавливаемся, когда следующий блок не влезает в суммарный
 * потолок. Выбрасывается СТАРОЕ: человек спрашивает про то, что случилось
 * только что, и обрезать свежее ради древнего было бы ровно наоборот.
 *
 * Возвращает `undefined`, когда отдавать нечего, — чтобы вызывающий не заводил
 * пустую часть сообщения и не рисовал плашку «уехало ноль команд».
 */
export function shellTail(
  blocks: readonly TailBlock[],
  n: number,
  labels: TailLabels
): ShellTail | undefined {
  const want = Math.max(0, Math.floor(n))
  if (!want || !blocks.length) return undefined

  const candidates = blocks.slice(-want)
  const chosen: Array<{ block: TailBlock; text: string }> = []
  let budget = TOTAL_CAP
  let dropped = 0

  for (let i = candidates.length - 1; i >= 0; i--) {
    const text = blockText(candidates[i], labels)
    /*
     * Самый свежий блок берём ВСЕГДА, даже если он один съедает весь потолок:
     * иначе на длинном выводе человек не получил бы ничего и не понял почему.
     * Его текст уже обрезан до `PER_BLOCK_CAP`, так что предел всё равно есть.
     */
    if (chosen.length && text.length > budget) {
      dropped = i + 1
      break
    }
    chosen.push({ block: candidates[i], text })
    budget -= text.length
  }

  chosen.reverse()
  if (!chosen.length) return undefined

  return {
    text: [labels.intro, '', ...chosen.map((c) => c.text)].join('\n'),
    used: chosen.map((c) => ({
      command: c.block.command,
      ...(c.block.exitCode === undefined ? {} : { exitCode: c.block.exitCode })
    })),
    dropped
  }
}
