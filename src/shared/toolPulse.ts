/**
 * Пульс инструмента: работает он ещё или уже умер.
 *
 * Пока агент выполняет команду, карточка показывала только наш секундомер. Он
 * идёт всегда — и когда `npm test` честно собирает проект, и когда процесс
 * повис намертво. То есть на экране «работает 4 минуты» и «висит 4 минуты»
 * выглядят одинаково, а это ровно те две новости, которые надо различать.
 *
 * Движок присылает `tool_progress` — сердцебиение живого вызова. Само его
 * наличие и есть ответ: пульс идёт — инструмент жив, пульс пропал — что-то не
 * так. Но сказать «пульса нет» можно только там, где он БЫЛ: SDK нигде не
 * обещает слать `tool_progress` для каждого инструмента, и молчание с самого
 * начала означает «движок про этот вызов не рассказывает», а не «вызов умер».
 * Объявить смерть по такому молчанию — та же ложь, только с другой стороны.
 *
 * Отсюда и порог: не выдуманная константа, а СВОЯ для каждого вызова —
 * измеренная по тому, как часто этот пульс приходил на самом деле.
 */

export interface ToolPulse {
  /** Когда пришёл последний пульс, мс эпохи. */
  lastAt: number
  /** Сколько всего пульсов пришло: по одному кадром цикл не измеряется. */
  beats: number
  /** Самый длинный промежуток между пульсами, мс, — наблюдённый, не заданный. */
  gapMax: number
  /** Сколько вызов уже идёт по часам ДВИЖКА, секунд. */
  elapsedSec: number
  /** Движок повторяет упавшую подзадачу — это новость, а не деталь. */
  retry?: { attempt: number; max: number }
}

/**
 * Ниже этого молчание ничего не значит.
 *
 * Даже при частом пульсе полминуты тишины — это ещё не смерть: между кадрами
 * стоит очередь IPC, сборщик мусора и занятый рендерер. Тревога, которая
 * срабатывает на обычную заминку, учит не читать тревоги.
 */
export const PULSE_QUIET_FLOOR_MS = 30_000

/** Во сколько раз тишина должна превысить наблюдённый ритм, чтобы стать новостью. */
const QUIET_FACTOR = 3

/** Учесть пришедший пульс. `prev` — то, что знали про этот вызов до него. */
export function notePulse(
  prev: ToolPulse | undefined,
  at: number,
  elapsedSec: number,
  retry?: { attempt: number; max: number }
): ToolPulse {
  if (!prev) return { lastAt: at, beats: 1, gapMax: 0, elapsedSec, retry }
  // Промежуток может прийти отрицательным, если часы дёрнулись: тогда он не
  // измерение, а мусор, и в ритм его брать нельзя.
  const gap = Math.max(0, at - prev.lastAt)
  return {
    lastAt: at,
    beats: prev.beats + 1,
    gapMax: Math.max(prev.gapMax, gap),
    elapsedSec,
    // Повтор не «залипает»: движок называет его заново на каждом кадре, пока
    // повторяет. Пропал из кадра — значит, повторять перестал.
    retry
  }
}

/**
 * Сколько длится тишина, о которой стоит сказать. `null` — сказать нечего.
 *
 * Молчим в двух случаях: пульса не было вовсе (движок про этот вызов не
 * рассказывает) и пульс был ровно один (ритм ещё не измерен — сравнивать не с
 * чем). Оба — про незнание, а не про смерть, и оба честнее показать пустым
 * местом.
 */
export function pulseSilence(pulse: ToolPulse | undefined, now: number): number | null {
  if (!pulse || pulse.beats < 2) return null
  const quiet = now - pulse.lastAt
  const limit = Math.max(pulse.gapMax * QUIET_FACTOR, PULSE_QUIET_FLOOR_MS)
  return quiet > limit ? quiet : null
}

/** Свежий ли пульс — то есть подтверждает ли движок прямо сейчас, что вызов жив. */
export function pulseAlive(pulse: ToolPulse | undefined, now: number): boolean {
  return !!pulse && pulseSilence(pulse, now) === null
}
