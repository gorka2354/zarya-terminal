/**
 * Чужой текст, который попадает в контекст агента МИМО человека.
 *
 * ПОВОД. У Зари таких путей два, и оба ведут из соседней панели: записка
 * (`send_to_pane`) и список панелей (`list_panes` — заголовок, папка и «чем
 * занят»). Человек их не читает и не одобряет: записка приходит сама, список
 * агент запрашивает сам, и карточки разрешения у обоих нет намеренно.
 *
 * Значит это недоверенный ввод того же класса, что текст с веб-страницы. И
 * опаснее он тем, что приходит ИЗНУТРИ приложения: модель склонна доверять
 * тому, что выглядит частью её собственного разговора.
 *
 * ЧТО ЭТО НЕ ЕСТЬ. Не граница безопасности. Она — в другом месте: чужой текст
 * не одобряет разрешений, а ход по записке идёт со снятым автопилотом, так что
 * любое действие всё равно упирается в гейт. Здесь мы только гасим маскировку
 * под служебный текст, чтобы модель не приняла чужие слова за слова системы.
 * Ровно так же честно называет свою защиту Anthropic для вывода субагента.
 *
 * ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Пути два, и правило у них общее. Написать его в
 * каждом значило бы завести две копии, которые однажды разойдутся, — а
 * разойдётся в них решение о том, что считать подделкой.
 */

/**
 * Невидимые символы, которыми ломают поиск по словам.
 *
 * Прогон нашёл дыру в прежней защите записки: она искала `[note from pane`
 * буквально, а `\s` в регулярных выражениях НЕ считает пробелом ни нулевой
 * ширины пробел, ни соединители. Достаточно вставить один такой символ между
 * словами — и подделка проходит нетронутой, оставаясь для модели читаемой.
 *
 * Поэтому сначала выбрасываем их вовсе: в записке соседа им делать нечего.
 *
 * СПИСКОМ ЗДЕСЬ НЕЛЬЗЯ. Сперва я перечислил шесть символов — и ревью тут же
 * прошло мимо них седьмым: `[note⁢from⁢pane]` с невидимым умножением остался
 * нетронутым. Перечисление всегда отстаёт от того, кто его читает, поэтому
 * берём свойство Юникода целиком: «символ, который по умолчанию не
 * отображается».
 *
 * Селекторы вариаций (FE00–FE0F) исключены намеренно: они тоже невидимы, но
 * ими собираются эмодзи, и выброси мы их — чужой текст поехал бы искажённым.
 * Обмануть ими правило нельзя: между буквами слова они не встают.
 */
const INVISIBLE = /(?![︀-️])\p{Default_Ignorable_Code_Point}/gu

/**
 * Скобки-двойники. Тот же обход: `［note from pane` выглядит как наша пометка,
 * а под правило для ASCII-скобки не попадает.
 */
const FAKE_BRACKETS: Array<[RegExp, string]> = [
  [/[［⟦⁅【〔]/g, '['],
  [/[］⟧⁆】〕]/g, ']'],
  [/[＜‹❮]/g, '<'],
  [/[＞›❯]/g, '>'],
  /*
   * Двоеточие — тоже. На нём держится единственное правило про границу хода
   * («Human:»), и ревью прошло мимо него полноширинным двойником: `Human：`
   * оставалось нетронутым. Приводим к обычному ДО разбора, иначе правило ниже
   * ищет то, чего в строке уже нет.
   */
  [/[：꞉ː∶﹕︓]/g, ':']
]

/**
 * Обороты, которыми чужой текст притворяется служебным.
 *
 * Список закрытый и короткий намеренно. Ловить «инструкции вообще» здесь
 * бессмысленно — обычная фраза «сделай X» неотличима от вредной, и решать это
 * должен гейт разрешений, а не поиск по строкам. Гасим только то, что
 * притворяется НЕ ТЕКСТОМ: границы ходов, системные пометки, наши собственные
 * маркеры.
 */
const DISGUISES: Array<[RegExp, string]> = [
  // Наша пометка авторства записки. Подделав её, сосед «становится» человеком.
  [/\[\s*note\s+from\s+pane/gi, '(note from pane'],
  // Маркеры хвоста консоли: закрыв их, чужой текст выдал бы себя за разговор.
  [/<\/?\s*untrusted-terminal-output\s*>/gi, '(marker stripped)'],
  // Системные пометки движка — то, чем он отделяет свои слова от чужих.
  [/<\/?\s*system-reminder\s*>/gi, '(tag stripped)'],
  [/<\/?\s*system\s*>/gi, '(tag stripped)'],
  // Границы ходов: ими рисуют поддельное «человек сказал».
  [/(^|\s)(Human|Assistant|System)\s*:/gi, '$1$2․'],
  // Имитация итога инструмента — им притворяются, чтобы выдать выдумку за факт.
  [/<\/?\s*(tool_result|tool_use|function_results?)\s*>/gi, '(tag stripped)']
]

/**
 * Обезвредить чужой текст, оставив его читаемым.
 *
 * Ничего не удаляем целиком и не переписываем смысл: человек должен увидеть в
 * ленте то же, что увидит модель, иначе пометка перестаёт быть проверяемой.
 * Меняем ровно форму — так, чтобы подделка перестала выглядеть служебной.
 */
export function defuse(text: string): string {
  let out = (text ?? '').replace(INVISIBLE, '')
  for (const [re, to] of FAKE_BRACKETS) out = out.replace(re, to)
  for (const [re, to] of DISGUISES) out = out.replace(re, to)
  return out
}

/**
 * Обезвредить МНОГОСТРОЧНЫЙ вывод чужой программы.
 *
 * Отличается от `defuseLine` ровно тем, что переводы строк остаются: вывод
 * команды без них нечитаем, а поддельный «конец сообщения» здесь и не нужен —
 * текст едет внутри маркеров, и опасна попытка эти маркеры закрыть.
 *
 * ЗАВЕДЕНА ПО РЕВЬЮ. Хвост консоли гасил подделку маркера с самого начала, а
 * `read_block` — новая дорога к тем же данным — отдавал вывод сырым. То есть
 * защита разошлась не копиями, как я опасался в шапке файла, а самим своим
 * наличием: в одном пути есть, в другом нет. Теперь обе дороги зовут это.
 */
export function defuseOutput(text: string): string {
  return defuse(text ?? '')
}

/**
 * То же, плюс схлопывание строк и предел длины — для короткого поля.
 *
 * Многострочный текст позволяет нарисовать в чужом промпте что угодно, включая
 * поддельный конец сообщения; записка и заголовок панели — одна-две фразы, и
 * переводы строк им не нужны.
 */
export function defuseLine(text: string, max: number): string {
  const flat = defuse(text)
    .replace(/[\r\n]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
  return flat.length > max ? `${flat.slice(0, max)}…` : flat
}
