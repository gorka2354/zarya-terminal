import { describe, expect, it } from 'vitest'
import { deskTitle } from '@shared/deskTitle'

/**
 * Подпись рабочего стола видят чаще всего остального в списке. До неё вкладка
 * называлась именем той панели, что была в ней активной: четыре разных проекта
 * показывались одним именем, и оно менялось от того, куда человек ткнул минуту
 * назад. Здесь проверяется, что подпись честная и устойчивая.
 */
describe('подпись рабочего стола', () => {
  it('имя, заданное руками, важнее любых догадок', () => {
    expect(deskTitle(['Заря', 'quiz-funnel'], 'Релиз 0.6')).toBe('Релиз 0.6')
  })

  it('пустое имя — не имя: собираем из панелей', () => {
    expect(deskTitle(['Заря', 'quiz-funnel'], '   ')).toBe('Заря + quiz-funnel')
  })

  it('одна панель — её название', () => {
    expect(deskTitle(['Заря'])).toBe('Заря')
  })

  it('четыре разных — два имени и остаток числом', () => {
    expect(deskTitle(['Заря', 'quiz-funnel', 'CV', 'duofitness'])).toBe('Заря + quiz-funnel +2')
  })

  it('три панели одного проекта — это один проект, а не «Заря + Заря»', () => {
    expect(deskTitle(['Заря', 'Заря', 'Заря'])).toBe('Заря')
  })

  it('безымянные панели не превращают подпись в мусор', () => {
    expect(deskTitle(['', '  '])).toBe('Терминал')
    expect(deskTitle(['', 'Заря'])).toBe('Заря')
  })
})
