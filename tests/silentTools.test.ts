import { describe, expect, it } from 'vitest'
import { readFileSync } from 'fs'
import { join } from 'path'

/**
 * СТОРОЖ ПРИ ЕДИНСТВЕННОМ ОСЛАБЛЕНИИ ГЕЙТА.
 *
 * Два наших инструмента разрешаются БЕЗ карточки: `list_panes` только читает
 * состав панелей, `send_to_pane` кладёт в чужую ленту помеченный чужой текст.
 * Ослабление названо вслух в коде и обосновано там же: карточка на каждую
 * записку превращала разговор двух панелей в модальный диалог, и вся затея
 * переставала работать сама.
 *
 * ПОЧЕМУ ТЕСТ ЧИТАЕТ ИСХОДНИК, А НЕ ЗОВЁТ ФУНКЦИЮ. Ослабление — два строковых
 * литерала в условии внутри драйвера, который тянет за собой Electron и живой
 * SDK. Вынести их в общий модуль ради удобства проверки было бы хуже: список
 * «молчаливых имён» в отдельном файле СНИЖАЕТ порог для третьего, а сейчас
 * этот порог работает — чтобы добавить имя, надо дописать его в тот самый `if`
 * под комментарием, объясняющим, почему их ровно два.
 *
 * Ревью inc-46 назвало это прямо: дешевле любой абстракции — тест, который
 * падает при появлении третьего.
 */
const SRC = readFileSync(join(process.cwd(), 'src/main/claudeCodeDriver.ts'), 'utf8')

/** Строка гейта: `if (toolName === '…' || toolName === '…') { resolve allow }`. */
const SILENT_LINE = /if \(toolName === 'mcp__zarya__[^)]*\) \{\s*\n\s*resolve\(\{ behavior: 'allow' \}\)/

describe('молчаливое разрешение — ровно два имени', () => {
  it('условие на месте и выглядит так, как мы его описали', () => {
    // Если условие переписали иначе, тест обязан упасть и заставить перечитать
    // сам гейт: молчаливый обход — не то место, где догадка допустима.
    expect(SRC).toMatch(SILENT_LINE)
  })

  it('имён в нём ровно два, и это записки', () => {
    const line = SRC.match(SILENT_LINE)?.[0] ?? ''
    const names = line.match(/mcp__zarya__[a-z_]+/g) ?? []
    expect(names).toEqual(['mcp__zarya__send_to_pane', 'mcp__zarya__list_panes'])
  })

  it('инструменты чтения консоли туда НЕ попали', () => {
    /*
     * `list_blocks`/`read_block` читают вывод команд человека, а сколько его
     * отдавать, он уже ответил настройкой хвоста. Пустить их мимо карточки
     * значило бы молча расширить собственное обещание.
     */
    const line = SRC.match(SILENT_LINE)?.[0] ?? ''
    expect(line).not.toContain('list_blocks')
    expect(line).not.toContain('read_block')
  })

  it('вопрос человеку карточку получает всегда — даже при автопилоте', () => {
    // Соседняя строка того же гейта. Свой второй способ спросить человека нам
    // не нужен именно поэтому: этот проходит мимо всех автопилотов.
    expect(SRC).toMatch(/if \(!isQuestion && !stop && !mark\?\.destructive/)
  })
})
